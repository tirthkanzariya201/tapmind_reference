import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { parse as parseYaml } from "yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function loadYaml(relativePath) {
  return parseYaml(fs.readFileSync(path.join(root, relativePath), "utf8"));
}

function packagesFromVersions(productBlock) {
  return [...(productBlock.native || []), ...(productBlock.wrappers || [])];
}

function versionMapForProduct(productBlock) {
  const map = new Map();
  for (const pkg of packagesFromVersions(productBlock)) {
    map.set(pkg.name, {
      package_version: pkg.package_version || "",
      native_built_on: pkg.native_built_on || "",
      latest: Boolean(pkg.latest),
    });
  }
  return map;
}

function main() {
  const matrix = loadYaml("feature_matrix.yaml");
  const versionsDoc = loadYaml("package_versions.yaml");
  const featureDefinitions = matrix.features;
  const productMeta = matrix.meta.products;

  const products = productMeta.map((meta) => {
    const versionBlock = versionsDoc.products[meta.id];
    if (!versionBlock) {
      throw new Error(`Missing product block in package_versions.yaml: ${meta.id}`);
    }

    const versions = versionMapForProduct(versionBlock);
    const matrixPackages = matrix.products[meta.id]?.packages || [];

    const packages = matrixPackages.map((pkg) => {
      const version = versions.get(pkg.name);
      if (!version) {
        throw new Error(`Package "${pkg.name}" missing in package_versions.yaml for ${meta.id}`);
      }

      const features = Object.fromEntries(
        Object.entries(pkg.features).map(([key, value]) => [
          key,
          {
            ...value,
            display_name: featureDefinitions[key]?.display_name || key,
          },
        ])
      );

      return {
        product_id: meta.id,
        product_name: meta.name,
        name: pkg.name,
        framework: pkg.framework,
        platform: pkg.platform,
        mediation: pkg.mediation,
        package_version: version.package_version,
        native_built_on: version.native_built_on,
        latest: version.latest,
        features,
      };
    });

    return {
      id: meta.id,
      name: meta.name,
      package_count: packages.length,
      packages,
    };
  });

  const payload = {
    generated_from: ["feature_matrix.yaml", "package_versions.yaml"],
    feature_definitions: featureDefinitions,
    feature_order: Object.keys(featureDefinitions),
    products,
  };

  const outDir = path.join(root, "snippets");
  fs.mkdirSync(outDir, { recursive: true });

  const tsContent = `/* eslint-disable */
/** AUTO-GENERATED by scripts/generate-matrix-data.mjs. Do not edit by hand. */
export const MATRIX_DATA = ${JSON.stringify(payload, null, 2)} as const;
`;

  fs.writeFileSync(path.join(outDir, "matrix-data.ts"), tsContent);
  console.log(`Generated snippets/matrix-data.ts (${products.reduce((n, p) => n + p.packages.length, 0)} packages)`);
}

main();
